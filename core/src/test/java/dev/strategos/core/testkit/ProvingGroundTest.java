package dev.strategos.core.testkit;

import static org.assertj.core.api.Assertions.assertThat;

import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import dev.strategos.core.content.MapManifest;
import dev.strategos.core.content.MapWaypoint;
import dev.strategos.core.content.StartSlot;
import dev.strategos.core.sim.nav.Dir;
import dev.strategos.core.sim.nav.Surface;
import dev.strategos.core.sim.nav.SurfaceGrid;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayDeque;
import java.util.BitSet;
import java.util.Map;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

/**
 * MAP-01.3 (spec §1.6 D rows 3–4): the generator is the source of truth. It is deterministic; the committed package's
 * manifest carries its terrain hash, start slots and waypoints; and the movement cases it is for are really there: from
 * the west start a unit reaches every start slot and waypoint (over the ramps, the fords, the bridges, the pass and the
 * gate), the mesa's top and the wall walkway, but never the ridge's top or the river's deep water.
 */
class ProvingGroundTest {
    private static ProvingGround ground;
    private static SurfaceGrid grid;
    private static BitSet reached;

    @BeforeAll
    static void build() {
        ground = ProvingGround.generate();
        grid = ground.voxels().grid();
        StartSlot west = ground.startSlots().get(0);
        reached = reachableFrom(west.x(), west.z(), layerAt(west.x(), west.y(), west.z()));
    }

    @Test
    void theGeneratorIsDeterministic() {
        assertThat(ProvingGround.generate().terrainHash()).isEqualTo(ground.terrainHash());
    }

    @Test
    void theCommittedManifestCarriesTheGeneratorsHashSlotsAndWaypoints() throws IOException {
        Path file = Path.of(System.getProperty("strategos.repoRoot"))
                .resolve("mod/src/devtools/resources/data/strategos/strategos/maps/proving_ground.json");
        MapManifest manifest = MapManifest.CODEC
                .parse(JsonOps.INSTANCE, JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)))
                .getOrThrow();

        assertThat(manifest.terrainHash())
                .as("the committed package was generated by this generator; else rerun ./gradlew :mod:runMapgen")
                .isEqualTo(ground.terrainHash());
        assertThat(manifest.startSlots()).isEqualTo(ground.startSlots());
        assertThat(manifest.waypoints()).isEqualTo(ground.waypoints());
        assertThat(manifest.palette()).isEqualTo(ProvingGround.PALETTE);
        assertThat(manifest.sizeX()).isEqualTo(ProvingGround.SIZE);
        assertThat(manifest.height()).isEqualTo(ProvingGround.HEIGHT);
    }

    @Test
    void everyStartSlotAndWaypointIsReachableFromTheWestStart() {
        for (StartSlot slot : ground.startSlots()) {
            assertThat(reachable(slot.x(), slot.y(), slot.z()))
                    .as("start slot %s", slot)
                    .isTrue();
        }
        for (Map.Entry<String, MapWaypoint> e : ground.waypoints().entrySet()) {
            MapWaypoint w = e.getValue();
            assertThat(reachable(w.x(), w.y(), w.z()))
                    .as("waypoint %s", e.getKey())
                    .isTrue();
        }
    }

    @Test
    void theRaisedPlacesAreReachedByTheirRampsAndStairsOnly() {
        assertThat(reachable(55, 23, 55)).as("the mesa's top").isTrue();
        assertThat(reachable(120, ground.top(120, 100) + 1, 100))
                .as("the cliff band's plateau")
                .isTrue();
        assertThat(reachable(316, 21, 241)).as("the yard's wall walkway").isTrue();
        assertThat(reachable(268, 31, 110))
                .as("the ridge's top, cliffs all round")
                .isFalse();
    }

    @Test
    void theRiverIsDeepExceptAtTheFords() {
        int deep = layerAt(ProvingGround.RIVER_X, 10, 160);
        int ford = layerAt(ProvingGround.RIVER_X, 11, 143);

        assertThat(Surface.kind(grid.surface(ProvingGround.RIVER_X, 160, deep))).isEqualTo(Surface.DEEP_WATER);
        assertThat(Surface.kind(grid.surface(ProvingGround.RIVER_X, 143, ford))).isEqualTo(Surface.SHALLOW_WATER);
        assertThat(reached.get(grid.node(ProvingGround.RIVER_X, 160, deep))).isFalse();
    }

    @Test
    void columnsStoreFromTheirLowestBlockThatIsNotStone() {
        int x = 30;
        int z = 30;
        assertThat(ground.lowestStored(x, z)).isEqualTo(ground.top(x, z));
        assertThat(ground.lowestStored(ProvingGround.RIVER_X, 160)).isEqualTo(9);
        for (int y = 0; y < ground.lowestStored(x, z); y++) {
            assertThat(ground.block(x, y, z)).isEqualTo(ProvingGround.STONE);
        }
    }

    private static boolean reachable(int x, int y, int z) {
        int layer = layerAt(x, y, z);
        return reached.get(grid.node(x, z, layer));
    }

    /** The layer of the column's surface whose floor is the bottom of block {@code y}. */
    private static int layerAt(int x, int y, int z) {
        for (int layer = 0; layer < grid.count(x, z); layer++) {
            if (Surface.floor(grid.surface(x, z, layer)) == y * 16) {
                return layer;
            }
        }
        throw new AssertionError("no surface at (" + x + ", " + y + ", " + z + ")");
    }

    private static BitSet reachableFrom(int x, int z, int layer) {
        BitSet seen = new BitSet();
        ArrayDeque<int[]> queue = new ArrayDeque<>();
        seen.set(grid.node(x, z, layer));
        queue.add(new int[] {x, z, layer});
        while (!queue.isEmpty()) {
            int[] at = queue.poll();
            if (!Surface.passable(grid.surface(at[0], at[1], at[2]))) {
                continue;
            }
            for (int dir = 0; dir < Dir.COUNT; dir++) {
                int next = grid.neighbour(at[0], at[1], at[2], dir);
                if (next < 0) {
                    continue;
                }
                int nx = at[0] + Dir.dx(dir);
                int nz = at[1] + Dir.dz(dir);
                if (!seen.get(grid.node(nx, nz, next))) {
                    seen.set(grid.node(nx, nz, next));
                    queue.add(new int[] {nx, nz, next});
                }
            }
        }
        return seen;
    }
}
